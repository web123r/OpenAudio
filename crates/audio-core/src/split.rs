pub fn receive_and_split_to_devices(
    bind_addr: &str,
    device_targets: Vec<Option<String>>,
    record_each_channel: bool,
    keep_running: Arc<AtomicBool>,
) -> Result<(), String> {
    receive_and_split_to_devices_with_cipher(
        bind_addr,
        device_targets,
        record_each_channel,
        None,
        keep_running,
    )
}

pub fn receive_and_split_to_devices_with_cipher(
    bind_addr: &str,
    device_targets: Vec<Option<String>>,
    record_each_channel: bool,
    cipher: Option<Arc<StreamCipher>>,
    keep_running: Arc<AtomicBool>,
) -> Result<(), String> {
    ensure_realtime_audio_thread();

    let socket = UdpSocket::bind(bind_addr)
        .map_err(|error| format!("failed to bind {bind_addr}: {error}"))?;

    socket
        .set_read_timeout(Some(Duration::from_millis(200)))
        .map_err(|error| format!("failed to set read timeout: {error}"))?;

    println!(
        "Split-receive listening on {bind_addr}, waiting for \
         first packet..."
    );

    // The OpenAudio protocol supports up to 255 channels. At 58
    // Float32 frames per packet, a 65,536-byte receive buffer safely
    // accommodates the largest packet currently generated by the
    // non-ASIO publishers.
    let mut packet_buffer = [0u8; 65_536];
    let mut decoder = AudioPacketDecoder::new();

    let (channel_count, sample_rate, first_pcm) = loop {
        if !keep_running.load(Ordering::Relaxed) {
            return Ok(());
        }

        match socket.recv_from(&mut packet_buffer) {
            Ok((packet_length, _source)) => {
                let raw_packet = &packet_buffer[..packet_length];
                let decrypted_buf: Vec<u8>;
                let packet: &[u8] = if let Some(ref c) = cipher {
                    if raw_packet.len() >= 6
                        && raw_packet[5] == network_core::protocol::PACKET_TYPE_AUDIO_ENCRYPTED
                    {
                        match crate::crypto::decrypt_audio_packet(c, raw_packet) {
                            Ok(dec) => {
                                decrypted_buf = dec;
                                &decrypted_buf
                            }
                            Err(_) => continue,
                        }
                    } else {
                        continue;
                    }
                } else {
                    raw_packet
                };

                if let Some(parsed) = parse_packet(packet) {
                    match decoder.decode(packet, &parsed) {
                        Ok(frames) => {
                            if let Some(frame) = frames.into_iter().next() {
                                break (
                                    frame.packet.channel_count as usize,
                                    frame.packet.sample_rate,
                                    frame.pcm,
                                );
                            }
                        }
                        Err(_) => continue,
                    }
                }
            }
            Err(ref error) if error.kind() == std::io::ErrorKind::WouldBlock => {
                continue;
            }
            Err(ref error) if error.kind() == std::io::ErrorKind::TimedOut => {
                continue;
            }
            Err(ref error) if error.kind() == std::io::ErrorKind::ConnectionReset => {
                continue;
            }
            Err(error) => {
                return Err(format!(
                    "recv error while waiting for first packet: \
                     {error}"
                ));
            }
        }
    };

    if channel_count == 0 {
        return Err("incoming split stream has zero channels".to_string());
    }

    println!("Detected {channel_count}ch @ {sample_rate}Hz.");

    if device_targets.len() != channel_count {
        return Err(format!(
            "got {} device target(s) but the incoming stream \
             has {channel_count} channel(s) -- these must match \
             exactly",
            device_targets.len()
        ));
    }

    // One meter channel represents one logical incoming network
    // channel, regardless of how many hardware channels the selected
    // output device uses.
    let (signal_meter, _signal_meter_guard) = register_scoped_signal_meter(
        format!("split-output:{bind_addr}"),
        format!("Split Subscribe — {bind_addr}"),
        SignalDirection::Output,
        channel_count,
    );

    let writers: Vec<Option<SharedWavWriter>> = if record_each_channel {
        let mut writers = Vec::with_capacity(channel_count);

        for channel_index in 0..channel_count {
            let path = generate_record_path(&format!("split_ch{channel_index}"));

            let writer = create_wav_writer(&path, 1, sample_rate).map_err(|error| {
                format!(
                    "failed to create split recording for \
                         channel {channel_index}: {error}"
                )
            })?;

            writers.push(Some(writer));
        }

        writers
    } else {
        vec![None; channel_count]
    };

    let per_channel_buffers: Vec<Arc<Mutex<VecDeque<f32>>>> = (0..channel_count)
        .map(|_| Arc::new(Mutex::new(VecDeque::new())))
        .collect();

    println!("Opening {channel_count} output device(s)...");

    let backend = get_backend();
    let mut streams = Vec::with_capacity(channel_count);
    let mut output_sample_rates = Vec::with_capacity(channel_count);

    for (channel_index, target) in device_targets.iter().enumerate() {
        let label = target
            .clone()
            .unwrap_or_else(|| "System Default".to_string());

        let (_device_label, output_config) = backend
            .get_output_config(target.as_deref())
            .map_err(|error| format!("channel {channel_index} ('{label}'): {error}"))?;

        let output_channels = output_config.channels as usize;
        if output_channels == 0 {
            return Err(format!(
                "channel {channel_index} ('{label}') exposes zero output channels"
            ));
        }
        let output_sample_rate = output_config.sample_rate;
        output_sample_rates.push(output_sample_rate);

        let buffer_for_callback = per_channel_buffers[channel_index].clone();

        let signal_meter_for_callback = signal_meter.clone();
        let logical_meter_channel = channel_index;

        let stream = backend
            .build_output_stream(
                target.as_deref(),
                Box::new(move |data: &mut [f32]| {
                    ensure_realtime_audio_thread();

                    let result = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
                        render_split_channel(data, output_channels, &buffer_for_callback);

                        signal_meter_for_callback.observe_channel(logical_meter_channel, data);
                    }));

                    if result.is_err() {
                        eprintln!(
                            "audio-core: panic caught in split \
                         callback — outputting silence this cycle"
                        );
                        data.fill(0.0);
                        signal_meter_for_callback.observe_channel(logical_meter_channel, data);
                    }
                }),
            )
            .map_err(|error| {
                format!(
                    "channel {channel_index} ('{label}'): \
                 failed to build stream: {error}"
                )
            })?;

        stream
            .play()
            .map_err(|error| format!("failed to start split stream: {error}"))?;

        streams.push(stream);
    }

    let mut resamplers = output_sample_rates
        .iter()
        .map(|&output_sample_rate| {
            StreamingLinearResampler::new(1, sample_rate, output_sample_rate)
        })
        .collect::<Result<Vec<_>, _>>()?;

    demux_into_pcm_buffers(
        &per_channel_buffers,
        &writers,
        &mut resamplers,
        &first_pcm,
        channel_count,
    )?;

    println!("All {channel_count} channel(s) playing. Streaming...");

    let mut packets_received = 1u32;

    while keep_running.load(Ordering::Relaxed) {
        let (packet_length, _source) = match socket.recv_from(&mut packet_buffer) {
            Ok(result) => result,
            Err(ref error)
                if error.kind() == std::io::ErrorKind::WouldBlock
                    || error.kind() == std::io::ErrorKind::TimedOut =>
            {
                // The socket went quiet: emit any Opus frame that has been
                // waiting for substreams, concealed, instead of stranding it.
                for frame in decoder.flush_expired()? {
                    if frame.packet.sample_rate != sample_rate {
                        continue;
                    }

                    packets_received = packets_received.saturating_add(1);

                    demux_into_pcm_buffers(
                        &per_channel_buffers,
                        &writers,
                        &mut resamplers,
                        &frame.pcm,
                        channel_count,
                    )?;
                }

                continue;
            }
            Err(ref error) if error.kind() == std::io::ErrorKind::ConnectionReset => {
                continue;
            }
            Err(error) => {
                return Err(format!("recv error: {error}"));
            }
        };

        let raw_packet = &packet_buffer[..packet_length];
        let decrypted_buf: Vec<u8>;
        let packet: &[u8] = if let Some(ref c) = cipher {
            if raw_packet.len() >= 6
                && raw_packet[5] == network_core::protocol::PACKET_TYPE_AUDIO_ENCRYPTED
            {
                match crate::crypto::decrypt_audio_packet(c, raw_packet) {
                    Ok(dec) => {
                        decrypted_buf = dec;
                        &decrypted_buf
                    }
                    Err(_) => continue,
                }
            } else {
                continue;
            }
        } else {
            raw_packet
        };

        let Some(parsed) = parse_packet(packet) else {
            continue;
        };

        if parsed.channel_count as usize != channel_count {
            eprintln!(
                "audio-core: split dropping packet -- \
                 format mismatch"
            );
            continue;
        }
        match decoder.decode(packet, &parsed) {
            Ok(frames) => {
                for frame in frames {
                    if frame.packet.sample_rate != sample_rate {
                        eprintln!(
                            "audio-core: split dropping packet -- \
                             format mismatch"
                        );
                        continue;
                    }

                    packets_received = packets_received.saturating_add(1);

                    demux_into_pcm_buffers(
                        &per_channel_buffers,
                        &writers,
                        &mut resamplers,
                        &frame.pcm,
                        channel_count,
                    )?;
                }
            }
            Err(error) => {
                eprintln!("audio-core: split decode error: {error}");
                continue;
            }
        }

        // Each split queue is mono, so trimming individual samples also
        // preserves frame alignment.
        for (channel_index, channel_buffer) in per_channel_buffers.iter().enumerate() {
            let maximum_samples =
                ((output_sample_rates[channel_index] as f64 * 0.2) as usize).max(1);
            let mut buffer = safe_lock(channel_buffer);

            while buffer.len() > maximum_samples {
                buffer.pop_front();
            }
        }
    }

    // Stop callbacks before finalizing writers or dropping buffers.
    drop(streams);

    for writer in writers.iter().flatten() {
        finalize_recording(writer);
    }

    println!(
        "Done. {packets_received} packets received across \
         {channel_count} channel(s)."
    );

    Ok(())
}

/// Renders one logical mono network channel to one physical device.
///
/// The mono source is duplicated across every output channel exposed
/// by the selected device.
fn render_split_channel(
    output: &mut [f32],
    output_channels: usize,
    source_buffer: &Arc<Mutex<VecDeque<f32>>>,
) {
    if output_channels == 0 {
        output.fill(0.0);
        return;
    }

    let frame_count = output.len() / output_channels;

    let mut buffer = safe_lock(source_buffer);

    for frame_index in 0..frame_count {
        let sample = buffer.pop_front().unwrap_or(0.0).clamp(-1.0, 1.0);

        let frame_offset = frame_index * output_channels;

        for output_channel in 0..output_channels {
            output[frame_offset + output_channel] = sample;
        }
    }

    // A CPAL callback is normally frame-aligned, but explicitly clear
    // any incomplete trailing samples if a backend violates that
    // assumption.
    let rendered_samples = frame_count * output_channels;

    if rendered_samples < output.len() {
        output[rendered_samples..].fill(0.0);
    }
}

fn demux_into_pcm_buffers(
    per_channel_buffers: &[Arc<Mutex<VecDeque<f32>>>],
    writers: &[Option<SharedWavWriter>],
    resamplers: &mut [StreamingLinearResampler],
    pcm: &[f32],
    channel_count: usize,
) -> Result<(), String> {
    if channel_count == 0
        || per_channel_buffers.len() < channel_count
        || writers.len() < channel_count
        || resamplers.len() < channel_count
    {
        return Err("split stream has inconsistent channel routing state".to_string());
    }

    if pcm.is_empty() {
        return Ok(());
    }

    let frame_count = pcm.len() / channel_count;
    if frame_count == 0 {
        return Ok(());
    }

    let mut channel_samples = vec![Vec::<f32>::with_capacity(frame_count); channel_count];

    for frame_index in 0..frame_count {
        let frame_offset = frame_index * channel_count;
        for channel_index in 0..channel_count {
            channel_samples[channel_index].push(pcm[frame_offset + channel_index]);
        }
    }

    for channel_index in 0..channel_count {
        let converted = resamplers[channel_index].process(&channel_samples[channel_index])?;

        {
            let mut destination = safe_lock(&per_channel_buffers[channel_index]);
            destination.extend(converted.iter().copied());
        }

        if let Some(writer) = &writers[channel_index] {
            write_samples(writer, &channel_samples[channel_index]);
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::AudioPacketDecoder;
    use crate::protocol::{parse_packet, PacketHeader};
    use network_core::opus::{MultichannelOpusEncoder, OPUS_FRAME_SAMPLES};
    use network_core::protocol::encode_opus_packet;

    #[test]
    fn split_opus_receiver_assembles_multichannel_frame() {
        let channel_count = 5;
        let samples = (0..OPUS_FRAME_SAMPLES)
            .flat_map(|frame| {
                (0..channel_count)
                    .map(move |channel| ((frame as f32 * 0.03) + channel as f32 * 0.2).sin() * 0.25)
            })
            .collect::<Vec<_>>();
        let mut encoder = MultichannelOpusEncoder::new(channel_count, 128_000).unwrap();
        let encoded = encoder.encode(&samples, 20).unwrap();
        let mut state = AudioPacketDecoder::new();
        let mut decoded = Vec::new();

        for (sub_stream_index, sequence_number, payload) in encoded {
            let packet = encode_opus_packet(
                &PacketHeader {
                    sub_stream_index,
                    stream_id: 88,
                    sequence_number,
                    presentation_timestamp_ns: 123_000,
                },
                channel_count as u8,
                48_000,
                OPUS_FRAME_SAMPLES as u16,
                &payload,
            )
            .unwrap();
            let parsed = parse_packet(&packet).unwrap();
            decoded = state.decode(&packet, &parsed).unwrap();
        }

        assert_eq!(decoded.len(), 1, "complete Opus frame decoded");
        assert_eq!(decoded[0].packet.presentation_timestamp_ns, 123_000);
        assert_eq!(decoded[0].pcm.len(), OPUS_FRAME_SAMPLES * channel_count);
        assert!(decoded[0].pcm.iter().all(|sample| sample.is_finite()));
    }
}
